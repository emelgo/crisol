export interface GameIcon {
  id: string
  label: string
  group: GameIconGroup
  author: string
}

export const GAME_ICONS: readonly GameIcon[] = LIST.map(([id, label, group, author]) => ({ id, label, group, author }))

const BY_ID = new Map(GAME_ICONS.map((icon) => [icon.id, icon]))

/** El icono de rol que dice un valor guardado («gi:dragon-head»), o null (un emoji, o uno que no está) */
export function gameIcon(value: string | null | undefined): GameIcon | null {
  if (!value?.startsWith('gi:')) return null
  return BY_ID.get(value.slice(3)) ?? null
}

